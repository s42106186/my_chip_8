#include "memory.h"

unsigned char memory[MEM_SIZE];

void ClearMemory()
{
  for(unsigned short i = 0x000; i < MEM_SIZE; ++i)
	  memory[i] = 0;
  return;
}

void WriteRomsToMemory()
{
  int fd = open("roms/chip8_logo.ch8", O_RDONLY);
  if(fd == -1) {
    perror("roms/chip8_logo.ch8");
    return;
  }

  struct stat st;
  if(fstat(fd, &st) == -1) {
    perror("stat error");
    return;
  }

  if(st.st_size <= (MEM_SIZE - RAM_SIZE)) {
    //0x200 - 0xFFF for roms
    ssize_t n = read(fd, memory+RAM_SIZE, st.st_size);
    if(n == -1) perror("read error");

  }else {
    printf("big size roms");
    return;
  } 
  close(fd);
  return;
}

